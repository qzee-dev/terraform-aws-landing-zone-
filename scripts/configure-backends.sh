#!/usr/bin/env bash
set -euo pipefail

script_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
repo_dir="$(cd "$script_dir/.." && pwd)"
bootstrap_dir="$repo_dir/bootstrap"

if ! command -v jq >/dev/null 2>&1; then
  echo "jq is required to generate backend configuration files." >&2
  exit 1
fi

configs="$(terraform -chdir="$bootstrap_dir" output -json environment_backend_configs)"
environments=(management security log-archive network shared-services workload-dev workload-stage workload-prod sandbox)

for environment in "${environments[@]}"; do
  backend_file="$repo_dir/environments/$environment/backend.hcl"
  if [[ -e "$backend_file" ]] && ! grep -q '^# Generated by scripts/configure-backends.sh$' "$backend_file"; then
    echo "Refusing to overwrite non-generated file: $backend_file" >&2
    echo "Move it aside or remove it, then rerun this script." >&2
    exit 1
  fi

  jq -e --arg environment "$environment" '
    .[$environment] |
    (.bucket | strings) and
    (.key | strings) and
    (.region | strings) and
    (.kms_key_id | strings) and
    (.account_id | strings) and
    (.role_arn | strings)
  ' <<<"$configs" >/dev/null
done

temp_file=""
trap 'if [[ -n "$temp_file" ]]; then rm -f "$temp_file"; fi' EXIT

for environment in "${environments[@]}"; do
  environment_dir="$repo_dir/environments/$environment"
  backend_file="$environment_dir/backend.hcl"

  content="$(jq -er --arg environment "$environment" '
    .[$environment] |
    "# Generated by scripts/configure-backends.sh\n" +
    "bucket = " + (.bucket | tojson) + "\n" +
    "key = " + (.key | tojson) + "\n" +
    "region = " + (.region | tojson) + "\n" +
    "encrypt = true\n" +
    "kms_key_id = " + (.kms_key_id | tojson) + "\n" +
    "use_lockfile = true\n" +
    "allowed_account_ids = [" + (.account_id | tojson) + "]\n" +
    "assume_role {\n  role_arn = " + (.role_arn | tojson) + "\n}\n"
  ' <<<"$configs")"

  temp_file="$(mktemp "$environment_dir/.backend.hcl.XXXXXX")"
  printf '%s' "$content" >"$temp_file"
  chmod 600 "$temp_file"
  mv -f "$temp_file" "$backend_file"
  temp_file=""
  printf 'Generated environments/%s/backend.hcl\n' "$environment"
done
